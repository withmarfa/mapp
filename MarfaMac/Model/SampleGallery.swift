    private static func picture(top: (Double, Double, Double), bottom: (Double, Double, Double)) -> Data {
        let size = CGSize(width: 640, height: 480)
        let image = NSImage(size: size, flipped: false) { rect in
            let gradient = NSGradient(
                starting: NSColor(red: top.0, green: top.1, blue: top.2, alpha: 1),
                ending: NSColor(red: bottom.0, green: bottom.1, blue: bottom.2, alpha: 1))
            gradient?.draw(in: rect, angle: 270)
            return true
        }
        guard let tiff = image.tiffRepresentation, let bitmap = NSBitmapImageRep(data: tiff) else { return Data() }
        return bitmap.representation(using: .png, properties: [:]) ?? Data()
    }

    /// A clip of a single gradient, written to a temporary file and read back: one second with no sound by default, or
    /// `seconds` long with a tone under it.
    private static func video(
        top: (Double, Double, Double), bottom: (Double, Double, Double), seconds: Int = 1, sound: Bool = false
    ) async -> Data {
        try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        let url = directory.appending(path: "clip-\(UUID().uuidString).mp4")
        defer { try? FileManager.default.removeItem(at: url) }
        guard let writer = try? AVAssetWriter(outputURL: url, fileType: .mp4) else { return Data() }
        let input = AVAssetWriterInput(mediaType: .video, outputSettings: [
            AVVideoCodecKey: AVVideoCodecType.h264, AVVideoWidthKey: 640, AVVideoHeightKey: 480])
        let attributes = CVPixelBufferCreationAttributes(
            pixelFormatType: CVPixelFormatType(rawValue: kCVPixelFormatType_32ARGB), size: CVImageSize(width: 640, height: 480))
        guard var buffer = try? CVMutablePixelBuffer(attributes) else { return Data() }
        buffer.accessUnsafeMutableRawPlaneBytes { planes in
            let (properties, bytes) = planes[0]
            for y in 0..<480 {
                let t = Double(y) / 479
                let color = [top.0 + (bottom.0 - top.0) * t, top.1 + (bottom.1 - top.1) * t, top.2 + (bottom.2 - top.2) * t].map { UInt8($0 * 255) }
                for x in 0..<640 {
                    let at = y * properties.bytesPerRow + x * 4
                    bytes[at] = 255; bytes[at + 1] = color[0]; bytes[at + 2] = color[1]; bytes[at + 3] = color[2]
                }
            }
        }
        let pixels = CVReadOnlyPixelBuffer(buffer)
        let receiver = writer.inputPixelBufferReceiver(for: input, pixelBufferAttributes: attributes)
        do {
            try writer.start()
            writer.startSession(atSourceTime: .zero)
            for frame in 0..<(30 * seconds) {
                try await receiver.append(pixels, with: CMTime(value: CMTimeValue(frame), timescale: 30))
            }
        } catch {
            writer.cancelWriting()
            return Data()
        }
        receiver.finish()
        await writer.finishWriting()
        guard sound else { return (try? Data(contentsOf: url)) ?? Data() }
        return await adding(soundOfSeconds: Double(seconds), to: url)
    }

    /// Mono 16-bit samples of a voice-like sound: a low tone with overtones, in phrases that swell and fall away with
    /// pauses between.
    private static func tone(seconds: Double, rate: Double = 22_050) -> [Int16] {
        let count = Int(seconds * rate)
        return (0..<count).map { index in
            let t = Double(index) / rate
            let phrase = max(0, sin(t * 0.9)) * (0.55 + 0.45 * sin(t * 7.3))
            let voice = sin(2 * .pi * 170 * t) + 0.5 * sin(2 * .pi * 340 * t) + 0.25 * sin(2 * .pi * 510 * t)
            return Int16(max(-1, min(1, voice * phrase * 0.5)) * 30_000)
        }
    }

    /// The tone as a WAV file, written to a temporary file the caller removes.
    private static func toneFile(seconds: Double) -> URL? {
        let rate: UInt32 = 22_050
        let samples = tone(seconds: seconds, rate: Double(rate))
        var data = Data()
        func put<T: FixedWidthInteger>(_ value: T) { withUnsafeBytes(of: value.littleEndian) { data.append(contentsOf: $0) } }
        let bytes = UInt32(samples.count * 2)
        data.append(contentsOf: Array("RIFF".utf8)); put(36 + bytes); data.append(contentsOf: Array("WAVEfmt ".utf8))
        put(UInt32(16)); put(UInt16(1)); put(UInt16(1)); put(rate); put(rate * 2); put(UInt16(2)); put(UInt16(16))
        data.append(contentsOf: Array("data".utf8)); put(bytes)
        for sample in samples { put(sample) }
        try? FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        let url = directory.appending(path: "tone-\(UUID().uuidString).wav")
        return (try? data.write(to: url)) == nil ? nil : url
    }

    /// A sound of `seconds`, as an M4A file's bytes.
    private static func sound(seconds: Double) async -> Data {
        guard let wav = toneFile(seconds: seconds) else { return Data() }
        defer { try? FileManager.default.removeItem(at: wav) }
        let out = directory.appending(path: "sound-\(UUID().uuidString).m4a")
        defer { try? FileManager.default.removeItem(at: out) }
        guard let session = AVAssetExportSession(asset: AVURLAsset(url: wav), presetName: AVAssetExportPresetAppleM4A) else { return Data() }
        do { try await session.export(to: out, as: .m4a) } catch { return Data() }
        return (try? Data(contentsOf: out)) ?? Data()
    }

    /// The clip at `url` with a tone laid under it.
    private static func adding(soundOfSeconds seconds: Double, to url: URL) async -> Data {
        guard let wav = toneFile(seconds: seconds) else { return Data() }
        defer { try? FileManager.default.removeItem(at: wav) }
        let out = directory.appending(path: "mixed-\(UUID().uuidString).mp4")
        defer { try? FileManager.default.removeItem(at: out) }
        let composition = AVMutableComposition()
        do {
            let picture = AVURLAsset(url: url)
            let voice = AVURLAsset(url: wav)
            for (source, kind) in [(picture, AVMediaType.video), (voice, .audio)] {
                guard let from = try await source.loadTracks(withMediaType: kind).first,
                      let into = composition.addMutableTrack(withMediaType: kind, preferredTrackID: kCMPersistentTrackID_Invalid)
                else { return Data() }
                try into.insertTimeRange(CMTimeRange(start: .zero, duration: CMTime(seconds: seconds, preferredTimescale: 600)), of: from, at: .zero)
            }
            guard let session = AVAssetExportSession(asset: composition, presetName: AVAssetExportPresetHighestQuality) else { return Data() }
            try await session.export(to: out, as: .mp4)
            return try Data(contentsOf: out)
        } catch {
            return Data()
        }
    }

    /// A report of 48 pages with contents, as the boards' long PDF has.
    private static func report() -> Data {
        let chapters = [
            ("The chair’s letter", [String]()), ("The year in numbers", ["Income", "Spending", "Reserves"]),
            ("The six projects", ["The boat shed", "Saturday school", "The orchard", "Warm rooms", "The archive", "Bursaries"]),
            ("Who gave", []), ("Trustees and staff", []), ("Accounts", []),
        ]
        let data = NSMutableData()
        var box = CGRect(x: 0, y: 0, width: 595, height: 842)
        guard let consumer = CGDataConsumer(data: data as CFMutableData),
              let context = CGContext(consumer: consumer, mediaBox: &box, nil) else { return Data() }
        let headings = chapters.flatMap { [$0.0] + $0.1 }
        // Every page after the cover runs under one heading, and the contents go to the first page of each.
        let heading = { (page: Int) in (page - 1) * headings.count / 47 }
        for page in 0..<48 {
            context.beginPDFPage(nil)
            NSGraphicsContext.saveGraphicsState()
            NSGraphicsContext.current = NSGraphicsContext(cgContext: context, flipped: false)
            NSColor.white.setFill()
            box.fill()
            if page == 0 {
                NSColor(red: 0.55, green: 0.7, blue: 0.85, alpha: 1).setFill()
                CGRect(x: 0, y: 442, width: 595, height: 400).fill()
                "LEWES TRUST".draw(at: CGPoint(x: 48, y: 380), withAttributes: [.font: NSFont.boldSystemFont(ofSize: 11), .foregroundColor: NSColor.systemGreen])
                "Annual report 2025".draw(at: CGPoint(x: 48, y: 320), withAttributes: [.font: NSFont(name: "Georgia-Bold", size: 44) ?? NSFont.boldSystemFont(ofSize: 44), .foregroundColor: NSColor.black])
            } else {
                headings[heading(page)].draw(at: CGPoint(x: 60, y: 760), withAttributes: [.font: NSFont.boldSystemFont(ofSize: 24), .foregroundColor: NSColor.black])
                for line in 0..<14 {
                    "Six projects, four hundred and twelve thousand pounds, and everyone who gave it."
                        .draw(at: CGPoint(x: 60, y: 700 - Double(line) * 40), withAttributes: [.font: NSFont.systemFont(ofSize: 12), .foregroundColor: NSColor.darkGray])
                }
                "\(page + 1)".draw(at: CGPoint(x: 290, y: 40), withAttributes: [.font: NSFont.systemFont(ofSize: 10), .foregroundColor: NSColor.gray])
            }
            NSGraphicsContext.restoreGraphicsState()
            context.endPDFPage()
        }
        // Written by Core Graphics as the file is made: an outline set through PDFKit is lost when it writes the file.
        func entry(_ label: String, children: [String] = []) -> [String: Any] {
            let index = headings.firstIndex(of: label) ?? 0
            let first = (1..<48).first { heading($0) == index } ?? 1
            var item: [String: Any] = [kCGPDFOutlineTitle as String: label, kCGPDFOutlineDestination as String: first + 1]
            if !children.isEmpty { item[kCGPDFOutlineChildren as String] = children.map { entry($0) } }
            return item
        }
        let outline = [kCGPDFOutlineChildren as String: chapters.map { entry($0.0, children: $0.1) }]
        CGPDFContextSetOutline(context, outline as CFDictionary)
        context.closePDF()
        return data as Data
    }

    private static func document(title: String, lines: [String]) -> Data {
        let data = NSMutableData()
        var box = CGRect(x: 0, y: 0, width: 595, height: 842)
        guard let consumer = CGDataConsumer(data: data as CFMutableData),
              let context = CGContext(consumer: consumer, mediaBox: &box, nil) else { return Data() }
        context.beginPDFPage(nil)
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(cgContext: context, flipped: false)
        NSColor.white.setFill()
        box.fill()
        title.draw(at: CGPoint(x: 60, y: 760), withAttributes: [.font: NSFont.boldSystemFont(ofSize: 30), .foregroundColor: NSColor.black])
        for (index, line) in lines.enumerated() {
            line.draw(at: CGPoint(x: 60, y: 690 - Double(index) * 40), withAttributes: [.font: NSFont.systemFont(ofSize: 20), .foregroundColor: NSColor.darkGray])
        }
        NSGraphicsContext.restoreGraphicsState()
        context.endPDFPage()
        context.closePDF()
        return data as Data
    }
